/* ---------- STATE ---------- */
const state = {
  topic: "Introduction to ICT",
  difficulty: "easy",
  questions: [],
  current: 0,
  score: 0,
  correct: 0,
  lives: 3,
  total: 10,
  answered: false
};

/* ---------- DOM REFS ---------- */
const $ = (id) => document.getElementById(id);
const startScreen = $("startScreen");
const gameScreen = $("gameScreen");
const resultScreen = $("resultScreen");
const topicGrid = $("topicGrid");
const difficultyButtons = $("difficultyButtons");
const startBtn = $("startBtn");
const quitBtn = $("quitBtn");
const questionText = $("questionText");
const paths = $("paths");
const paths2 = $("paths2");
const feedback = $("feedback");
const scoreDisplay = $("scoreDisplay");
const levelDisplay = $("levelDisplay");
const livesDisplay = $("livesDisplay");
const progressText = $("progressText");
const topicBadge = $("topicBadge");
const playAgainBtn = $("playAgainBtn");

/* ---------- BUILD TOPIC BUTTONS ---------- */
Object.keys(QUESTION_BANK).forEach((topic) => {
  const btn = document.createElement("button");
  btn.className = "topic-btn";
  btn.textContent = topic;
  btn.dataset.topic = topic;
  if (topic === state.topic) btn.classList.add("active");
  btn.addEventListener("click", () => {
    document.querySelectorAll(".topic-btn").forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    state.topic = topic;
  });
  topicGrid.appendChild(btn);
});

/* ---------- DIFFICULTY SELECT ---------- */
difficultyButtons.querySelectorAll(".diff-btn").forEach((btn) => {
  btn.addEventListener("click", () => {
    difficultyButtons.querySelectorAll(".diff-btn").forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    state.difficulty = btn.dataset.diff;
  });
});

/* ---------- START GAME ---------- */
startBtn.addEventListener("click", startGame);
playAgainBtn.addEventListener("click", () => {
  resultScreen.classList.remove("active");
  startScreen.classList.add("active");
});

quitBtn.addEventListener("click", () => {
  if (confirm("Quit the game? Your progress will be lost.")) {
    gameScreen.classList.remove("active");
    startScreen.classList.add("active");
  }
});

function startGame() {
  // Prepare questions
  const pool = QUESTION_BANK[state.topic] || QUESTION_BANK["Introduction to ICT"];
  state.questions = shuffle([...pool]).slice(0, Math.min(state.total, pool.length));
  state.current = 0;
  state.score = 0;
  state.correct = 0;
  state.lives = state.difficulty === "hard" ? 2 : state.difficulty === "medium" ? 3 : 3;
  state.answered = false;

  updateHUD();
  topicBadge.textContent = state.topic;

  startScreen.classList.remove("active");
  gameScreen.classList.add("active");
  renderQuestion();
}

/* ---------- RENDER QUESTION ---------- */
function renderQuestion() {
  state.answered = false;
  feedback.className = "feedback";
  feedback.textContent = "";

  const q = state.questions[state.current];
  questionText.textContent = q.q;

  const allPaths = [...paths.querySelectorAll(".path"), ...paths2.querySelectorAll(".path")];

  // Build shuffled options with tracking of correct index
  const optionData = q.options.map((opt, i) => ({ text: opt, isCorrect: i === q.correct }));
  const shuffled = shuffle(optionData);

  allPaths.forEach((btn, i) => {
    const opt = shuffled[i];
    btn.querySelector(".path-text").textContent = opt.text;
    btn.dataset.correct = opt.isCorrect ? "true" : "false";
    btn.classList.remove("correct", "wrong");
    btn.disabled = false;
  });

  // Hide second row if only 2 options
  paths2.style.display = allPaths.length > 2 ? "flex" : "none";

  progressText.textContent = `Question ${state.current + 1} of ${state.questions.length}`;
  updateHUD();
}

/* ---------- HANDLE ANSWER ---------- */
[...paths.querySelectorAll(".path"), ...paths2.querySelectorAll(".path")].forEach((btn) => {
  btn.addEventListener("click", () => {
    if (state.answered) return;
    state.answered = true;

    const q = state.questions[state.current];
    const isCorrect = btn.dataset.correct === "true";

    // Disable all
    document.querySelectorAll(".path").forEach((b) => (b.disabled = true));

    if (isCorrect) {
      btn.classList.add("correct");
      state.correct++;
      state.score += state.difficulty === "hard" ? 20 : state.difficulty === "medium" ? 15 : 10;
      feedback.className = "feedback success show";
      feedback.textContent = `✅ Correct! ${q.explanation}`;
    } else {
      btn.classList.add("wrong");
      state.lives--;
      // Highlight correct answer
      document.querySelectorAll(".path").forEach((b) => {
        if (b.dataset.correct === "true") b.classList.add("correct");
      });
      feedback.className = "feedback error show";
      feedback.textContent = `❌ Wrong. ${q.explanation}`;
    }

    updateHUD();

    // Next or end
    setTimeout(() => {
      if (state.lives <= 0) return endGame(false);
      state.current++;
      if (state.current >= state.questions.length) return endGame(true);
      renderQuestion();
    }, 1600);
  });
});

/* ---------- HUD ---------- */
function updateHUD() {
  scoreDisplay.textContent = state.score;
  levelDisplay.textContent = Math.min(state.current + 1, state.questions.length || 1);
  livesDisplay.textContent = "❤️".repeat(Math.max(state.lives, 0)) || "💔";
}

/* ---------- END GAME ---------- */
function endGame(completed) {
  gameScreen.classList.remove("active");
  resultScreen.classList.add("active");

  const total = state.questions.length;
  const accuracy = total > 0 ? Math.round((state.correct / total) * 100) : 0;

  $("finalScore").textContent = state.score;
  $("finalCorrect").textContent = `${state.correct}/${total}`;
  $("finalAccuracy").textContent = `${accuracy}%`;

  if (state.lives <= 0) {
    $("resultTitle").textContent = "💔 Out of Lives!";
    $("resultMessage").textContent = "Don't give up — review the topic and try again!";
  } else if (accuracy >= 80) {
    $("resultTitle").textContent = "🏆 Excellent!";
    $("resultMessage").textContent = "You're an ICT champion! Keep it up!";
  } else if (accuracy >= 50) {
    $("resultTitle").textContent = "👍 Good Job!";
    $("resultMessage").textContent = "You're getting there. Practice makes perfect!";
  } else {
    $("resultTitle").textContent = "📚 Keep Learning!";
    $("resultMessage").textContent = "Review the topic and try again — you'll improve!";
  }
}

/* ---------- UTIL ---------- */
function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

